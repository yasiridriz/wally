#!/bin/sh
# Copy the Google keys from the web app's .env.local into Config/Secrets.xcconfig.
# The script never prints key values.
set -eu
cd "$(dirname "$0")/.."
env_file="../.env.local"
[ -f "$env_file" ] || { echo "Missing $env_file" >&2; exit 1; }
read_value() { sed -n "s/^$1=//p" "$env_file" | tail -n 1 | sed 's/^"//; s/"$//'; }
umask 077
{
  echo "// Generated by scripts/sync-secrets.sh from ../.env.local. Do not commit."
  echo "WALLY_GOOGLE_MAPS_SDK_KEY = $(read_value NEXT_PUBLIC_GOOGLE_MAPS_API_KEY)"
  echo "WALLY_GOOGLE_PLACES_ROUTES_KEY = $(read_value GOOGLE_MAPS_API_KEY)"
  echo "WALLY_GOOGLE_MAPS_MAP_ID = $(read_value NEXT_PUBLIC_GOOGLE_MAPS_MAP_ID)"
} > Config/Secrets.xcconfig
for name in WALLY_GOOGLE_MAPS_SDK_KEY WALLY_GOOGLE_PLACES_ROUTES_KEY WALLY_GOOGLE_MAPS_MAP_ID; do
  if grep -q "^$name = ..*" Config/Secrets.xcconfig; then echo "$name: set"; else echo "$name: empty"; fi
done
